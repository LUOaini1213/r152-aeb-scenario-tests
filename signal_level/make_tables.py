"""Markdown tables for README.md / report.md section 10, generated from results/*.csv (no hand-copied numbers).

Run:  python -B -I signal_level/make_tables.py   -> results/tables_signal_level.md
"""
import csv
import json
import sys
from collections import Counter
from pathlib import Path

sys.dont_write_bytecode = True
RES = Path(__file__).resolve().parent / "results"
ZH_CFG = {"original": "原参数", "proposed": "新参数"}
ZH_VAR = {"U": "基线 U", "H": "H 保持", "R": "R 快恢复", "HR": "HR 保持+快恢复"}


def load(name):
    with open(RES / name, encoding="utf-8") as f:
        return list(csv.DictReader(f))


def f(x, nd=1):
    return "-" if x in ("", "None", None) else f"{float(x):.{nd}f}"


def yes(x):
    return "是" if x == "True" else "否"


def table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" if i == 0 else "---:" for i in range(len(head))) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return out


def main():
    L = ["<!-- generated by signal_level/make_tables.py from results/*.csv - do not edit by hand -->", ""]
    # ---------------------------------------------------------------- E1
    s = load("e1_equivalence_summary.csv")
    L += ["### 表 S1  无故障总线 vs P5 直连闭环（49 点 × 5 相位 × 2 套参数 = 490 次）", ""]
    rows = []
    for r in s:
        if r["protocol"] == "worst-over-phases":
            continue
        rows.append([r["mode"], r["protocol"], r["runs"], r["identical_runs"], f(r["max_abs_dv_kph"], 2),
                     r.get("contact_flips") or "0", r.get("r152_verdict_flips") or "0",
                     r.get("ncap_colour_flips") or "0", f(r.get("max_abs_dt_brake_s") or 0, 2)])
    L += table(["总线模式", "规程", "运行数", "与 P5 完全一致", "最大 \\|Δ碰撞速度\\| km/h", "碰撞有无翻转",
                "R152 判定翻转", "NCAP 颜色翻转", "最大 \\|Δ制动起点\\| s"], rows)
    w = next((r for r in s if r["protocol"] == "worst-over-phases"), None)
    if w:
        L += ["", f"按 P5 的口径（每点 5 个相位取最差）：{w['runs']} 个（点 × 参数）组合中 {w['identical_runs']} 个最差碰撞速度不变，"
                  f"最大差 {f(w['max_abs_dv_kph'], 2)} km/h。"]
    e = load("e1_quantization_explained.csv")
    kinds = Counter((x.get("kind") or "?").split(":")[0] for x in e)
    esc = [x for x in e if (x.get("kind") or "").startswith("escalation")]
    thr = Counter(max(x["state_direct"], x["state_dbc"], key=lambda k: ["OFF", "STANDBY", "FCW", "PARTIAL_BRAKE",
                                                                         "FULL_BRAKE", "FAULT"].index(k)) for x in esc)
    errs = sorted(abs(float(x["ttc_dbc_quantized"]) - float(x["ttc_direct_float"])) * 1000 for x in esc)
    L += ["", f"差异解释（`e1_quantization_explained.csv`，共 {len(e)} 次）：升级阈值跨越 {kinds.get('escalation threshold', 0)} 次"
              f"（预警 {thr.get('FCW', 0)}、部分制动 {thr.get('PARTIAL_BRAKE', 0)}、全力制动 {thr.get('FULL_BRAKE', 0)}），"
              f"制动释放条件（接近速度 ≤ 0.1 m/s）提前/推后一帧 {kinds.get('release', 0)} 次。"
              f"升级类差异处 |TTC_量化 − TTC_浮点| 的中位数 {errs[len(errs) // 2]:.1f} ms，最大 {errs[-1]:.1f} ms。", ""]
    # ---------------------------------------------------------------- E2
    s = load("e2_loss_summary.csv")
    L += ["### 表 S2  随机丢帧（所有报文独立同分布），R152 官方 6 点 × 5 相位 × 20 个种子", ""]
    rows = [[ZH_VAR[r["variant"]], ZH_CFG[r["config"]], f"{float(r['loss']) * 100:g}%", r["runs"],
             f"{r['impact_fail_runs']}（{float(r['impact_fail_share']) * 100:.1f}%）", r["lead_fail_runs"],
             r["demand_fail_runs"], r["fault_runs"], f"{f(r['worst_impact_kph'])}（{r['worst_case']}，限值 {f(r['worst_case_limit_kph'], 0)}）",
             yes(r["r152_pass_all_runs"])] for r in s]
    L += table(["降级策略", "参数", "丢帧率", "运行数", "碰撞超限运行", "预警提前量不足", "制动需求<5", "出现 FAULT",
                "最差碰撞 km/h", "全部运行通过"], rows)
    L += ["", "注：丢帧率 0 时结果确定，只跑 1 个种子（30 次）。“全部运行通过”同时看 5.2.1.4 碰撞速度、5.2.1.1 预警提前量、"
              "5.2.1.2 制动需求（字面），原参数因 4 m/s² 部分制动在 0 % 时就不满足 5.2.1.2。", ""]
    bc = load("e2_loss_by_case.csv")
    L += ["### 表 S3  丢帧 20 % 时各官方点最差碰撞速度与 R152 限值（km/h）", ""]
    rows = []
    for r in bc:
        if r["loss"] == "0.2":
            rows.append([ZH_VAR[r["variant"]], ZH_CFG[r["config"]], r["case_id"], f(r["limit_kph"], 0),
                         f(r["fault_free_worst_kph"]), f(r["worst_impact_kph"]), f(r["delta_kph"]),
                         f(r["margin_to_limit_kph"]), f"{r['impact_fail_runs']}/{r['runs']}"])
    L += table(["策略", "参数", "试验点", "限值", "无故障最差", "丢帧最差", "Δ", "距限值余量", "超限运行"], rows) + [""]
    # ---------------------------------------------------------------- E3
    s = load("e3_burst_by_duration.csv")
    L += ["### 表 S4  关键时刻突发丢帧（全总线），起点 = 无故障制动起点 + 偏移（−0.5…+0.5 s，步长 0.1 s），6 点 × 5 相位", ""]
    rows = [[ZH_VAR[r["variant"]], ZH_CFG[r["config"]], f"{float(r['duration_s']) * 1000:.0f} ms",
             f"{r['impact_fail_runs']}/{r['runs']}", r["lead_fail_runs"], r["fail_at_offset_0"] + "/30",
             r["offsets_with_impact_fail"] or "无",
             f"{f(r['worst_impact_kph'])}（{r['worst_case']}，偏移 {float(r['worst_offset_s']):+.1f} s，限值 {f(r['worst_limit_kph'], 0)}）"]
            for r in s]
    L += table(["策略", "参数", "突发时长", "碰撞超限", "预警提前量不足", "偏移 0 时超限", "出现超限的偏移 s", "最差碰撞 km/h"], rows)
    L += ["", "策略：U = 上游原样（输入故障 → FAULT 立即松制动，输入恢复后再等 fault_recover_s = 1.0 s）；"
              "H = 制动中遇通信故障保持当前减速度（AEB ECU 与制动 ECU 两侧，最长 2 s 或到停车）；"
              "R = 只把 AebConfig.fault_recover_s 从 1.0 s 改为 0.2 s（参数，不改代码）；HR = H + R。H/R/HR 是本项目提出的改进方案，不是上游行为。", ""]
    # ---------------------------------------------------------------- E4
    s = load("e4_latency_summary.csv")
    L += ["### 表 S5  总线附加时延（每帧），R152 19 点 × 5 相位", ""]
    rows = [[ZH_CFG[r["config"]], f"{float(r['latency_s']) * 1000:g}", f"{float(r['jitter_s']) * 1000:g}", r["runs"],
             r["impact_fail_points"], r["lead_fail_points"], r["demand_fail_points"], f(r["max_worst_dv_kph"]),
             f(r["worst_impact_kph"]), f"{float(r['mean_dt_brake_s']) * 1000:.0f} / {float(r['max_dt_brake_s']) * 1000:.0f}",
             f(r["min_gap_min_m"], 2)] for r in s]
    L += table(["参数", "时延 ms", "抖动 ms", "运行数", "碰撞超限点(/19)", "预警不足点", "需求<5 点", "最差碰撞增量 km/h",
                "最差碰撞 km/h", "制动起点推迟 均值/最大 ms", "最小车距 m"], rows) + [""]
    # ---------------------------------------------------------------- E5a
    s = load("e5_crc_detection.csv")
    L += ["### 表 S6  CRC-8（Profile 1）与 DBC 范围检查的检出能力（8 字节帧内翻转 k 个比特）", ""]
    rows = [[r["message"], r["flipped_bits"], r["method"], r["patterns"], f"{float(r['crc_detection_rate']) * 100:.2f}%",
             r["crc_undetected"], f"{float(r['range_check_rate_of_changed']) * 100:.1f}%" if r["range_check_rate_of_changed"] else "-"]
            for r in s]
    L += table(["报文", "翻转比特数", "方法", "样本数", "CRC 检出率", "CRC 漏检数", "范围检查检出率（仅改变了信号值的样本）"], rows)
    L += [""]
    # ---------------------------------------------------------------- E5b
    s = load("e5_corruption_summary.csv")
    L += ["### 表 S7  单帧单比特损坏（RADAR_TGT，T0 起每 100 ms 注入一次），有/无 E2E", ""]
    rows = [[r["variant"], ZH_CFG[r["config"]], r["case_id"], r["signal"], r["runs"], r["corrupted_frames_accepted"],
             r["early_brake_runs"], r["late_or_missed_runs"], r["early_warning_only_runs"], f(r["max_early_brake_s"], 2),
             f(r["max_ttc_at_early_brake_s"], 2), f(r["max_dv_kph"]), r["r152_impact_fail_runs"], r["r152_lead_fail_runs"]]
            for r in s]
    L += table(["校验", "参数", "试验点", "信号", "注入次数", "损坏帧被采用", "误制动/提前制动", "制动推迟/中断",
                "仅提前预警", "最大提前 s", "误制动时真实 TTC 最大 s", "最大碰撞增量 km/h", "碰撞超限", "预警提前量不足"], rows)
    L += [""]
    # ---------------------------------------------------------------- E6
    s = load("e6_fault_reaction.csv")
    summ = json.loads((RES / "summary_signal_level.json").read_text(encoding="utf-8")).get("e6", {})
    L += [f"### 表 S8  故障注入实测（{summ.get('case', '')}，{ZH_CFG.get(summ.get('config', ''), '')}，相位 0；无故障制动起点 "
          f"{summ.get('ref_t_brake', '')} s）", ""]
    rows = [[r["id"], r["fault"], f(r["t_start"], 2), f"{float(r['duration_s']) * 1000:.0f}", r["first_detection"],
             f(r["detect_delay_s"], 3), f(r["telltale_delay_s"], 3), f(r["telltale_off_after_end_s"], 2),
             f(r["brake_lost_s"], 3), f(r["v_rel_impact_kph"]), f(r["fcw_lead_s"], 2)] for r in s]
    L += table(["编号", "注入的故障", "开始 s", "时长 ms", "检测（监控器:类型@时刻）", "检测延迟 s", "报警灯延迟 s",
                "故障结束后报警灯熄灭 s", "制动请求丢失 s", "碰撞速度 km/h", "FCW 提前量 s"], rows)
    (RES / "tables_signal_level.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote results/tables_signal_level.md")


if __name__ == "__main__":
    main()
