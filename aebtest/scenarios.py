"""OpenSCENARIO side: compute the scenario parameters of a test point, write / read the grid files.

The grid of every protocol is stored as an OpenSCENARIO 1.2 ParameterValueDistribution
(scenarios/*_grid.xosc).  The closed loop (esmini backend AND the pure-Python fallback backend) reads its
parameter values from these files, so both backends run exactly the same test points.
"""
from __future__ import annotations

import xml.etree.ElementTree as ET
from dataclasses import dataclass
from pathlib import Path

from .regulations import (NCAP_CCRB_T0_BEFORE_DECEL_S, NCAP_T0_TTC_S, R152_TTC_START_S, TestPoint,
                          ncap_points, r152_points)

SCEN_DIR = Path(__file__).resolve().parents[1] / "scenarios"

# ---- project choices (not from R152 / Euro NCAP) ----
PRE_ROLL_S = 2.0        # steady driving before T0 (R152 6.4/6.5 ask for >= 2 s straight approach)
EGO_START_S = 50.0      # Ego reference point s on the 2 km road
SIM_END_S = 25.0        # hard stop of the storyboard; the closed loop normally ends much earlier
FREE_ROAD_GAP_M = 300.0 # SOTIF free-road cases: lead vehicle beyond the radar range (SensorParams.max_range_m)

GRID_FILES = {          # grid file -> (scenario file, selector)
    "R152_stationary_grid.xosc": ("CCRs.xosc", lambda p: p.protocol == "R152" and p.family == "CCRs"),
    "R152_moving_grid.xosc": ("CCRm.xosc", lambda p: p.protocol == "R152" and p.family == "CCRm"),
    "NCAP_CCRs_grid.xosc": ("CCRs.xosc", lambda p: p.protocol == "NCAP" and p.family == "CCRs"),
    "NCAP_CCRm_grid.xosc": ("CCRm.xosc", lambda p: p.protocol == "NCAP" and p.family == "CCRm"),
    "NCAP_CCRb_grid.xosc": ("CCRb.xosc", lambda p: p.protocol == "NCAP" and p.family == "CCRb"),
    "SOTIF_grid.xosc": ("CCRm.xosc", lambda p: p.protocol == "SOTIF"),
}


@dataclass(frozen=True)
class Geometry:
    ego_front_m: float      # Ego front bumper ahead of the Ego reference point
    target_rear_m: float    # Target rear bumper relative to the Target reference point (negative = behind)


def read_geometry(xosc: Path) -> Geometry:
    """Bumper offsets from the BoundingBox of Ego / Target in a scenario file."""
    root = ET.parse(xosc).getroot()
    off = {}
    for obj in root.iter("ScenarioObject"):
        bb = obj.find("./Vehicle/BoundingBox")
        cx = float(bb.find("Center").get("x"))
        length = float(bb.find("Dimensions").get("length"))
        off[obj.get("name")] = (cx, length)
    cx, ln = off["Ego"]
    tx, tl = off["Target"]
    return Geometry(ego_front_m=cx + ln / 2.0, target_rear_m=tx - tl / 2.0)


def scenario_params(tp: TestPoint, geo: Geometry) -> dict[str, object]:
    """OpenSCENARIO parameter values for one test point (speeds m/s, distances m, times s)."""
    v_e, v_t = tp.v_ego_kph / 3.6, tp.v_target_kph / 3.6
    p: dict[str, object] = {"CaseId": tp.case_id, "EgoSpeed": v_e, "TargetSpeed": v_t,
                            "EgoStartS": EGO_START_S, "SimEndTime": SIM_END_S}
    if tp.family == "CCRb":
        gap0 = tp.headway_s * v_e                          # Euro NCAP: time headway 1.0 s, equal speeds
        p["TargetDecel"] = tp.decel_mps2
        p["DecelStartTime"] = PRE_ROLL_S + NCAP_CCRB_T0_BEFORE_DECEL_S   # T0 = decel start - 1 s
    elif tp.protocol == "SOTIF":
        gap0 = FREE_ROAD_GAP_M                             # nothing real in radar range: phantom-object tests
    else:
        ttc0 = NCAP_T0_TTC_S if tp.protocol == "NCAP" else R152_TTC_START_S   # both 4.0 s
        gap0 = (ttc0 + PRE_ROLL_S) * (v_e - v_t)           # T0 reached after the pre-roll
    p["TargetStartS"] = EGO_START_S + geo.ego_front_m + gap0 - geo.target_rear_m
    return p


def sotif_points() -> list[TestPoint]:
    """Free-road runs (lead vehicle at equal speed 300 m ahead, outside radar range) for phantom-object tests."""
    return [TestPoint(f"SOTIF-FREE-{v}", "CCRm", "SOTIF", v, v, label="free road") for v in (60, 100)]


def regulatory_points() -> list[TestPoint]:
    return r152_points(sweep=True) + ncap_points()


def all_points() -> list[TestPoint]:
    return regulatory_points() + sotif_points()


def write_grids(points: list[TestPoint] | None = None) -> list[Path]:
    points = points or all_points()
    out = []
    for grid, (scen, select) in GRID_FILES.items():
        geo = read_geometry(SCEN_DIR / scen)
        sel = [p for p in points if select(p)]
        root = ET.Element("OpenSCENARIO")
        ET.SubElement(root, "FileHeader", revMajor="1", revMinor="2", date="2026-10-27T00:00:00",
                      author="Luo Wenjie (AI-assisted)",
                      description=f"Test grid for {scen}: {len(sel)} points (generated by scripts/make_scenarios.py)")
        dist = ET.SubElement(root, "ParameterValueDistribution")
        ET.SubElement(dist, "ScenarioFile", filepath=scen)
        vs = ET.SubElement(ET.SubElement(ET.SubElement(dist, "Deterministic"),
                                         "DeterministicMultiParameterDistribution"), "ValueSetDistribution")
        for p in sel:
            pvs = ET.SubElement(vs, "ParameterValueSet")
            for k, v in scenario_params(p, geo).items():
                ET.SubElement(pvs, "ParameterAssignment", parameterRef=k,
                              value=v if isinstance(v, str) else f"{v:.6f}")
        ET.indent(root, space="  ")
        path = SCEN_DIR / grid
        ET.ElementTree(root).write(path, encoding="UTF-8", xml_declaration=True)
        out.append(path)
    return out


def read_grid(grid: str) -> tuple[str, list[dict[str, str]]]:
    """(scenario file, [parameter dict per permutation]) from a ParameterValueDistribution file."""
    root = ET.parse(SCEN_DIR / grid).getroot()
    dist = root.find("ParameterValueDistribution")
    scen = dist.find("ScenarioFile").get("filepath")
    sets = [{a.get("parameterRef"): a.get("value") for a in pvs.iter("ParameterAssignment")}
            for pvs in dist.iter("ParameterValueSet")]
    return scen, sets


def read_declared_defaults(scen: str) -> dict[str, str]:
    root = ET.parse(SCEN_DIR / scen).getroot()
    return {d.get("name"): d.get("value") for d in root.find("ParameterDeclarations").iter("ParameterDeclaration")}


def grid_index() -> dict[str, tuple[str, str, int, dict[str, str]]]:
    """case_id -> (grid file, scenario file, permutation index, parameters)."""
    idx = {}
    for grid in GRID_FILES:
        scen, sets = read_grid(grid)
        for i, s in enumerate(sets):
            idx[s["CaseId"]] = (grid, scen, i, s)
    return idx
