"""Write results/tables_deepening.md (Chinese tables for report.md) from the run_deepening.py outputs.
Run:  python -I scripts/make_tables_deepening.py
"""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results"
ZH = {"green": "绿", "yellow": "黄", "orange": "橙", "brown": "棕", "red": "红"}
CFG = {"original": "原参数", "proposed": "新参数（干路调参）", "friction_aware_0.7": "摩擦自适应 μ0.7 档",
       "friction_aware_0.5": "摩擦自适应 μ0.5 档"}


def load(n):
    return list(csv.DictReader(open(RES / n, encoding="utf-8")))


def main():
    wet_sum, wet = load("wet_summary.csv"), load("wet_results.csv")
    search, ghost = load("wet_schedule_search.csv"), load("sotif_ghost.csv")
    rng_sum, rng = load("sotif_range_summary.csv"), load("sotif_range.csv")
    deep = json.loads((RES / "deepening_summary.json").read_text(encoding="utf-8"))
    L = ["<!-- generated by scripts/make_tables_deepening.py - do not edit by hand -->", "",
         "### 表 9  湿滑路面（模型内参考评价）：R152 + Euro NCAP 网格，5 个采样相位取最差", "",
         "| 参数组 | μ | 可达减速度 m/s² | R152 碰撞速度不通过（/19） | R152 任一条不通过（/19） | NCAP 简化估计（/5.2） | 红格（/30） | 二次接触运行数 |",
         "|---|---:|---:|---:|---:|---:|---:|---:|"]
    lim = deep["decel_limit_mps2"]
    for r in wet_sum:
        L.append(f"| {CFG[r['config']]} | {r['road_mu']} | {float(lim[str(float(r['road_mu']))]):.1f} | "
                 f"{r['r152_impact_fail_points']} | {r['r152_any_fail_points']} | {float(r['ncap_total']):.2f} | "
                 f"{r['red_cells']} | {r['late_contact_runs']} |")
    L += ["", "### 表 10  湿滑路面下 R152 关键点的余量（最差相位）", "",
          "| 试验点 | 限值 km/h | 原参数 μ0.9 | 原参数 μ0.7 | 原参数 μ0.5 | 新参数 μ0.5 |", "|---|---:|---|---|---|---|"]
    def cell(cfg, mu, cid):
        r = next(x for x in wet if x["config"] == cfg and x["road_mu"] == mu and x["case_id"] == cid)
        v = float(r["v_rel_impact_worst_kph"])
        return f"{v:.1f} km/h" if v > 0 else f"0（最小间距 {float(r['min_gap_m']):.2f} m）"
    import sys
    sys.path.insert(0, str(ROOT))
    from aebtest.regulations import r152_max_rel_impact_kph
    for cid, vrel in (("R152-S40", 40), ("R152-S42", 42), ("R152-S50", 50), ("R152-S55", 55), ("R152-S60", 60)):
        lim_v = min(r152_max_rel_impact_kph(vrel, m) for m in (("max_mass",) if cid == "R152-S40" else ("running_order",)))
        L.append(f"| {cid} | {lim_v:g} | {cell('original', '0.9', cid)} | {cell('original', '0.7', cid)} | "
                 f"{cell('original', '0.5', cid)} | {cell('proposed', '0.5', cid)} |")
    L += ["", "### 表 11  摩擦自适应阈值的选择结果（规则同干路参数搜索，候选 39 组/每个 μ）", "",
          "| μ | 选中 TTC 预警/部分/全力 s | NCAP 简化估计 | R152 约束 | 二次接触运行数 | 备注 |", "|---:|---|---:|---|---:|---|"]
    for mu, v in deep["friction_aware"].items():
        row = next(r for r in search if r["road_mu"] == mu and float(r["ttc_pb_s"]) == v["ttc_pb_s"]
                   and float(r["ttc_fb_s"]) == v["ttc_fb_s"])
        edge = "部分制动阈值落在搜索上界 3.2 s" if v["ttc_pb_s"] >= 3.2 else ""
        L.append(f"| {mu} | {v['ttc_fcw_s']:g} / {v['ttc_pb_s']:g} / {v['ttc_fb_s']:g} | {float(row['ncap_total']):.2f} | "
                 f"{'满足' if row['r152_ok'] == 'True' else '不满足'} | {row['late_contact_runs']} | {edge} |")
    L += ["", "### 表 12  幻影静止目标（自由路，干路），只出现 1 帧（50 ms）/ 300 ms", "",
          "| 参数组 | 幻影 TTC s | 1 帧：反应 | 1 帧：速度损失 km/h | 300 ms：反应 | 300 ms：速度损失 km/h |",
          "|---|---:|---|---:|---|---:|"]
    def react(r):
        req = float(r["max_decel_request_mps2"])
        return f"制动 {req:g} m/s² × {float(r['brake_time_s']):.1f} s" if req > 0 else ("仅预警" if r["fcw"] == "True" else "无")
    for cfg in ("original", "proposed", "friction_aware_0.5"):
        for t in ("2.8", "1.8", "1.2"):
            a = next(r for r in ghost if r["config"] == cfg and r["road_mu"] == "0.9" and r["case_id"] == "SOTIF-FREE-100"
                     and r["ghost_ttc_s"] == t and r["ghost_visible_s"] == "0.05")
            b = next(r for r in ghost if r["config"] == cfg and r["road_mu"] == "0.9" and r["case_id"] == "SOTIF-FREE-100"
                     and r["ghost_ttc_s"] == t and r["ghost_visible_s"] == "0.3")
            L.append(f"| {CFG[cfg]} | {t} | {react(a)} | {max(0.0, float(a['speed_loss_kph'])):.1f} | {react(b)} | "
                     f"{max(0.0, float(b['speed_loss_kph'])):.1f} |")
    L += ["", "（60 km/h 与 100 km/h 的结果相同：误制动持续时间由 brake_min_dwell_s = 0.5 s 决定，速度损失 ≈ 减速度 × 0.5 s。）",
          "", "### 表 13  雨天探测距离缩短（假设值）：R152 官方 + 扫描点", "",
          "| 参数组 | μ | 探测距离 m | R152 预警提前量不足的点 | 最小提前量 s | R152 碰撞速度不通过 | NCAP 简化估计 |",
          "|---|---:|---:|---|---:|---:|---:|"]
    for r in rng_sum:
        sub = [x for x in rng if x["config"] == r["config"] and x["road_mu"] == r["road_mu"]
               and x["max_range_m"] == r["max_range_m"] and x["case_id"].startswith("R152")]
        leads = [float(x["fcw_lead_min_s"]) for x in sub if x["fcw_lead_min_s"] not in ("", "None")]
        short = [x["case_id"] for x in sub if x["fcw_lead_min_s"] not in ("", "None") and float(x["fcw_lead_min_s"]) < 0.8 - 1e-9]
        L.append(f"| {CFG[r['config']]} | {r['road_mu']} | {float(r['max_range_m']):g} | {' '.join(short) or '-'} | "
                 f"{min(leads):.2f} | {r['r152_impact_fail_points']} | {float(r['ncap_total']):.2f} |")
    (RES / "tables_deepening.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote results/tables_deepening.md")


if __name__ == "__main__":
    main()
